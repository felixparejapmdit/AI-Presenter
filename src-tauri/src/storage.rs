//! Local project and image asset management.
//!
//! Layout: `<data>/vanguard-deck/projects/{project_id}/assets/{sha256}.{ext}`.
//! Files are content addressed, so re-importing the same screenshot is a no-op
//! and asset URLs are immutable.

use std::fs;
use std::io::{Cursor, Write};
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};

use base64::Engine;
use image::metadata::Orientation;
use image::{ImageDecoder, ImageFormat};
use serde::Serialize;
use sha2::{Digest, Sha256};
use tauri::{AppHandle, Manager, State};

const MAX_IMAGE_BYTES: usize = 64 * 1024 * 1024;

static TEMP_COUNTER: AtomicU64 = AtomicU64::new(0);

pub struct StorageState {
    pub root: PathBuf,
    pub db_url: String,
}

#[derive(Debug, Serialize, Clone)]
#[serde(rename_all = "camelCase")]
pub struct StorageInfo {
    pub data_dir: String,
    pub projects_dir: String,
    pub db_url: String,
}

#[derive(Debug, Serialize, Clone, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct StoredAsset {
    pub id: String,
    pub file_name: String,
    pub stored_name: String,
    pub path: String,
    pub mime: String,
    pub width: u32,
    pub height: u32,
    pub byte_size: u64,
}

pub fn resolve_data_dir(app: &AppHandle) -> Result<PathBuf, String> {
    if let Some(custom) = std::env::var_os("VANGUARD_DATA_DIR") {
        if !custom.is_empty() {
            return Ok(PathBuf::from(custom));
        }
    }
    app.path()
        .data_dir()
        .map(|dir| dir.join("vanguard-deck"))
        .map_err(|e| e.to_string())
}

pub fn database_url(root: &Path) -> String {
    format!("sqlite:{}", root.join("vanguard.db").display())
}

/// Project ids become directory names, so anything but a plain token is refused.
pub fn validate_project_id(project_id: &str) -> Result<(), String> {
    let valid = !project_id.is_empty()
        && project_id.len() <= 64
        && project_id
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_');
    if valid {
        Ok(())
    } else {
        Err(format!("Invalid project id: {project_id}"))
    }
}

/// Stored names are generated by `store_image`, so they never hold a separator.
pub fn validate_stored_name(name: &str) -> Result<(), String> {
    let valid = !name.is_empty()
        && name.len() <= 128
        && !name.starts_with('.')
        && name
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '.' || c == '-' || c == '_');
    if valid {
        Ok(())
    } else {
        Err(format!("Invalid asset name: {name}"))
    }
}

fn assets_dir(root: &Path, project_id: &str) -> Result<PathBuf, String> {
    validate_project_id(project_id)?;
    Ok(root.join("projects").join(project_id).join("assets"))
}

fn format_details(format: ImageFormat) -> Option<(&'static str, &'static str)> {
    match format {
        ImageFormat::Png => Some(("png", "image/png")),
        ImageFormat::Jpeg => Some(("jpg", "image/jpeg")),
        ImageFormat::WebP => Some(("webp", "image/webp")),
        ImageFormat::Gif => Some(("gif", "image/gif")),
        ImageFormat::Bmp => Some(("bmp", "image/bmp")),
        _ => None,
    }
}

/// Validates by sniffing bytes and reading only the header, so a 20 MB
/// screenshot is stored without being decoded.
pub fn store_image(root: &Path, project_id: &str, file_name: &str, bytes: &[u8]) -> Result<StoredAsset, String> {
    let dir = assets_dir(root, project_id)?;
    if bytes.is_empty() {
        return Err("The image is empty.".to_string());
    }
    if bytes.len() > MAX_IMAGE_BYTES {
        return Err("The image is larger than the 64 MB limit.".to_string());
    }

    let reader = image::ImageReader::new(Cursor::new(bytes))
        .with_guessed_format()
        .map_err(|e| e.to_string())?;
    let format = reader
        .format()
        .ok_or_else(|| "This file is not a supported image.".to_string())?;
    let (extension, mime) =
        format_details(format).ok_or_else(|| "Use a PNG, JPEG, WebP, GIF or BMP image.".to_string())?;
    let mut decoder = reader
        .into_decoder()
        .map_err(|_| "This image file appears to be corrupted.".to_string())?;
    let (raw_width, raw_height) = decoder.dimensions();
    // Webviews display photos upright using their EXIF orientation, so the recorded size
    // must match what is shown, or a phone photo would be squashed into the wrong shape.
    let orientation = decoder.orientation().unwrap_or(Orientation::NoTransforms);
    let (width, height) = if swaps_axes(orientation) {
        (raw_height, raw_width)
    } else {
        (raw_width, raw_height)
    };

    let digest = Sha256::digest(bytes);
    let hex: String = digest.iter().map(|byte| format!("{byte:02x}")).collect();
    let stored_name = format!("{hex}.{extension}");
    let destination = dir.join(&stored_name);

    if !destination.exists() {
        fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
        write_atomic(&destination, bytes)?;
    }

    Ok(StoredAsset {
        id: hex,
        file_name: sanitize_display_name(file_name),
        stored_name,
        path: destination.to_string_lossy().to_string(),
        mime: mime.to_string(),
        width,
        height,
        byte_size: bytes.len() as u64,
    })
}

fn swaps_axes(orientation: Orientation) -> bool {
    matches!(
        orientation,
        Orientation::Rotate90 | Orientation::Rotate270 | Orientation::Rotate90FlipH | Orientation::Rotate270FlipH
    )
}

fn sanitize_display_name(name: &str) -> String {
    let base = name.rsplit(['/', '\\']).next().unwrap_or("").trim();
    if base.is_empty() {
        "image".to_string()
    } else {
        base.to_string()
    }
}

/// Writes through a temp file so a crash cannot leave a half-written file behind.
fn write_atomic(destination: &Path, bytes: &[u8]) -> Result<(), String> {
    // Unique per write, so overlapping saves of one project cannot collide.
    let unique = TEMP_COUNTER.fetch_add(1, Ordering::Relaxed);
    let temp = destination.with_extension(format!("tmp{}-{unique}", std::process::id()));
    let result = (|| -> std::io::Result<()> {
        let mut file = fs::File::create(&temp)?;
        file.write_all(bytes)?;
        file.sync_all()?;
        fs::rename(&temp, destination)
    })();
    if result.is_err() {
        let _ = fs::remove_file(&temp);
    }
    result.map_err(|e| e.to_string())
}

fn decode_header_value(value: &str) -> String {
    // The frontend percent-encodes file names because headers must be ASCII.
    let bytes = value.as_bytes();
    let mut output = Vec::with_capacity(bytes.len());
    let mut index = 0;
    while index < bytes.len() {
        if bytes[index] == b'%' && index + 2 < bytes.len() {
            let hex = std::str::from_utf8(&bytes[index + 1..index + 3]).unwrap_or("");
            if let Ok(byte) = u8::from_str_radix(hex, 16) {
                output.push(byte);
                index += 3;
                continue;
            }
        }
        output.push(bytes[index]);
        index += 1;
    }
    String::from_utf8_lossy(&output).into_owned()
}

#[tauri::command]
pub fn get_storage_info(state: State<'_, StorageState>) -> StorageInfo {
    StorageInfo {
        data_dir: state.root.to_string_lossy().to_string(),
        projects_dir: state.root.join("projects").to_string_lossy().to_string(),
        db_url: state.db_url.clone(),
    }
}

/// Receives image bytes as a raw IPC body, avoiding the cost of JSON encoding a
/// multi-megabyte array, and writes them off the main thread.
#[tauri::command]
pub async fn save_image_asset(
    state: State<'_, StorageState>,
    request: tauri::ipc::Request<'_>,
) -> Result<StoredAsset, String> {
    let header = |name: &str| -> Option<String> {
        request
            .headers()
            .get(name)
            .and_then(|value| value.to_str().ok())
            .map(decode_header_value)
    };
    let project_id = header("x-project-id").ok_or("Missing project id")?;
    let file_name = header("x-file-name").unwrap_or_else(|| "image".to_string());
    let tauri::ipc::InvokeBody::Raw(bytes) = request.body() else {
        return Err("Expected a raw image body.".to_string());
    };
    let bytes = bytes.clone();
    let root = state.root.clone();

    tauri::async_runtime::spawn_blocking(move || store_image(&root, &project_id, &file_name, &bytes))
        .await
        .map_err(|e| e.to_string())?
}

#[tauri::command]
pub async fn import_image_from_path(
    state: State<'_, StorageState>,
    project_id: String,
    path: String,
) -> Result<StoredAsset, String> {
    let root = state.root.clone();
    tauri::async_runtime::spawn_blocking(move || {
        let size = fs::metadata(&path).map_err(|e| format!("Could not read the file: {e}"))?.len();
        if size > MAX_IMAGE_BYTES as u64 {
            return Err("The image is larger than the 64 MB limit.".to_string());
        }
        let bytes = fs::read(&path).map_err(|e| format!("Could not read the file: {e}"))?;
        store_image(&root, &project_id, &path, &bytes)
    })
    .await
    .map_err(|e| e.to_string())?
}

#[tauri::command]
pub async fn read_asset_base64(
    state: State<'_, StorageState>,
    project_id: String,
    stored_name: String,
) -> Result<String, String> {
    let root = state.root.clone();
    tauri::async_runtime::spawn_blocking(move || {
        validate_stored_name(&stored_name)?;
        let path = assets_dir(&root, &project_id)?.join(&stored_name);
        let bytes = fs::read(&path).map_err(|e| format!("Could not read the asset: {e}"))?;
        Ok::<String, String>(base64::engine::general_purpose::STANDARD.encode(bytes))
    })
    .await
    .map_err(|e| e.to_string())?
}

/// Mirrors a project to JSON beside its assets, giving a portable recovery copy
/// alongside SQLite.
#[tauri::command]
pub async fn write_project_snapshot(
    state: State<'_, StorageState>,
    project_id: String,
    json: String,
) -> Result<(), String> {
    let root = state.root.clone();
    tauri::async_runtime::spawn_blocking(move || {
        validate_project_id(&project_id)?;
        let dir = root.join("projects").join(&project_id);
        fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
        write_atomic(&dir.join("project.json"), json.as_bytes())
    })
    .await
    .map_err(|e| e.to_string())?
}

#[tauri::command]
pub async fn delete_project_files(state: State<'_, StorageState>, project_id: String) -> Result<(), String> {
    let root = state.root.clone();
    tauri::async_runtime::spawn_blocking(move || {
        validate_project_id(&project_id)?;
        let dir = root.join("projects").join(&project_id);
        if dir.exists() {
            fs::remove_dir_all(&dir).map_err(|e| e.to_string())?;
        }
        Ok::<(), String>(())
    })
    .await
    .map_err(|e| e.to_string())?
}

/// A JPEG carrying a minimal EXIF block with one orientation tag, as phone cameras write.
#[cfg(test)]
pub(crate) fn jpeg_with_orientation(width: u32, height: u32, orientation: u16) -> Vec<u8> {
    let image = image::RgbImage::from_pixel(width, height, image::Rgb([10, 20, 30]));
    let mut encoded = Cursor::new(Vec::new());
    image.write_to(&mut encoded, ImageFormat::Jpeg).unwrap();
    let jpeg = encoded.into_inner();

    let mut exif = Vec::new();
    exif.extend_from_slice(b"Exif\0\0II*\0");
    exif.extend_from_slice(&8u32.to_le_bytes());
    exif.extend_from_slice(&1u16.to_le_bytes());
    exif.extend_from_slice(&0x0112u16.to_le_bytes());
    exif.extend_from_slice(&3u16.to_le_bytes());
    exif.extend_from_slice(&1u32.to_le_bytes());
    exif.extend_from_slice(&orientation.to_le_bytes());
    exif.extend_from_slice(&[0, 0]);
    exif.extend_from_slice(&0u32.to_le_bytes());

    let mut output = vec![0xFF, 0xD8, 0xFF, 0xE1];
    output.extend_from_slice(&((exif.len() + 2) as u16).to_be_bytes());
    output.extend_from_slice(&exif);
    output.extend_from_slice(&jpeg[2..]);
    output
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn recorded_size_matches_how_a_rotated_photo_is_displayed() {
        let root = temp_root("exif");
        let rotated = store_image(&root, "p1", "phone.jpg", &jpeg_with_orientation(400, 300, 6)).unwrap();
        assert_eq!((rotated.width, rotated.height), (300, 400));
        let upright = store_image(&root, "p1", "camera.jpg", &jpeg_with_orientation(400, 300, 1)).unwrap();
        assert_eq!((upright.width, upright.height), (400, 300));
        let _ = fs::remove_dir_all(&root);
    }

    fn temp_root(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("vanguard-test-{name}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();
        dir
    }

    fn png_bytes(width: u32, height: u32) -> Vec<u8> {
        let image = image::RgbImage::from_pixel(width, height, image::Rgb([20, 40, 60]));
        let mut output = Cursor::new(Vec::new());
        image.write_to(&mut output, ImageFormat::Png).unwrap();
        output.into_inner()
    }

    #[test]
    fn project_ids_cannot_escape_the_projects_directory() {
        for bad in ["", "..", "../evil", "a/b", "a\\b", "C:\\x", "a b", "a.b"] {
            assert!(validate_project_id(bad).is_err(), "{bad} should be refused");
        }
        assert!(validate_project_id("3f2a9c1e-77aa-4e11-9d10-000000000001").is_ok());
    }

    #[test]
    fn stored_names_cannot_escape_the_assets_directory() {
        for bad in ["", "..", ".hidden", "../x.png", "a/b.png", "a\\b.png"] {
            assert!(validate_stored_name(bad).is_err(), "{bad} should be refused");
        }
        assert!(validate_stored_name("abc123.png").is_ok());
    }

    #[test]
    fn store_image_records_dimensions_and_dedupes_by_content() {
        let root = temp_root("dedupe");
        let bytes = png_bytes(320, 180);
        let first = store_image(&root, "p1", "C:\\Shots\\hero.png", &bytes).unwrap();
        let second = store_image(&root, "p1", "renamed.png", &bytes).unwrap();

        assert_eq!((first.width, first.height), (320, 180));
        assert_eq!(first.mime, "image/png");
        assert_eq!(first.file_name, "hero.png");
        assert_eq!(first.path, second.path);
        assert!(Path::new(&first.path).exists());
        assert_eq!(fs::read_dir(Path::new(&first.path).parent().unwrap()).unwrap().count(), 1);
        let _ = fs::remove_dir_all(&root);
    }

    #[test]
    fn store_image_rejects_non_images_and_bad_projects() {
        let root = temp_root("reject");
        assert!(store_image(&root, "p1", "note.txt", b"plain text").is_err());
        assert!(store_image(&root, "p1", "empty.png", b"").is_err());
        assert!(store_image(&root, "../evil", "a.png", &png_bytes(2, 2)).is_err());
        let _ = fs::remove_dir_all(&root);
    }

    #[test]
    fn header_values_decode_percent_encoding() {
        assert_eq!(decode_header_value("Q3%20Revenue.png"), "Q3 Revenue.png");
        assert_eq!(decode_header_value("r%C3%A9sum%C3%A9.png"), "r\u{e9}sum\u{e9}.png");
        assert_eq!(decode_header_value("100%"), "100%");
    }

    #[test]
    fn database_url_uses_the_sqlite_scheme() {
        let url = database_url(Path::new("D:/data"));
        assert!(url.starts_with("sqlite:D:/data"));
        assert!(url.ends_with("vanguard.db"));
    }
}
